-- Read-only, run by the agent: plan and result of every SQL of reports/wikipedia-content-md-backfill.yaml,
-- before the nightly run picks the manifest up. The page counts must use the link and reference tables'
-- unique key for a loose index scan ("Using index for group-by"), not a scan of every link.

EXPLAIN SELECT COUNT(*) FROM (SELECT DISTINCT ID_WIKIDATA, LANG FROM T_WC_WIKIPEDIA_PAGE_LANG_LINK) AS PAGES;
EXPLAIN SELECT COUNT(*) FROM (SELECT DISTINCT ID_WIKIDATA FROM T_WC_WIKIPEDIA_PAGE_LANG_LINK) AS ENTITIES;
EXPLAIN SELECT COUNT(*) FROM (SELECT DISTINCT ID_WIKIDATA, LANG FROM T_WC_WIKIPEDIA_PAGE_LANG_REFERENCE) AS PAGES;
EXPLAIN SELECT COUNT(*) FROM T_WC_WIKIPEDIA_PAGE_LANG_SECTION WHERE TIM_UPDATED >= NOW() - INTERVAL 1 DAY AND CONTENT_MD IS NOT NULL;
EXPLAIN SELECT COUNT(*) FROM T_WC_WIKIPEDIA_PAGE_LANG_LINK WHERE TIM_UPDATED >= NOW() - INTERVAL 1 DAY AND IS_REDLINK = 0 AND IS_DATE = 0;

SELECT 'content_md_page_backfill' AS METRIC,
  (SELECT COUNT(*) FROM (SELECT DISTINCT ID_WIKIDATA, LANG FROM T_WC_WIKIPEDIA_PAGE_LANG_LINK) AS PAGES) AS DONE,
  (SELECT COUNT(*) FROM T_WC_WIKIPEDIA_PAGE_LANG WHERE PAGE_EXISTS = 1) AS EXPECTED
UNION ALL SELECT 'content_md_entity_backfill',
  (SELECT COUNT(*) FROM (SELECT DISTINCT ID_WIKIDATA FROM T_WC_WIKIPEDIA_PAGE_LANG_LINK) AS ENTITIES),
  (SELECT COUNT(DISTINCT ID_WIKIDATA) FROM T_WC_WIKIPEDIA_PAGE_LANG WHERE PAGE_EXISTS = 1)
UNION ALL SELECT 'content_md_reference_pages',
  (SELECT COUNT(*) FROM (SELECT DISTINCT ID_WIKIDATA, LANG FROM T_WC_WIKIPEDIA_PAGE_LANG_REFERENCE) AS PAGES),
  (SELECT COUNT(*) FROM T_WC_WIKIPEDIA_PAGE_LANG WHERE PAGE_EXISTS = 1)
UNION ALL SELECT 'content_md_section_fill_last_day',
  (SELECT COUNT(*) FROM T_WC_WIKIPEDIA_PAGE_LANG_SECTION WHERE TIM_UPDATED >= NOW() - INTERVAL 1 DAY AND CONTENT_MD IS NOT NULL),
  (SELECT COUNT(*) FROM T_WC_WIKIPEDIA_PAGE_LANG_SECTION WHERE TIM_UPDATED >= NOW() - INTERVAL 1 DAY)
UNION ALL SELECT 'content_md_link_resolution_last_day',
  (SELECT COUNT(*) FROM T_WC_WIKIPEDIA_PAGE_LANG_LINK WHERE TIM_UPDATED >= NOW() - INTERVAL 1 DAY AND IS_REDLINK = 0 AND IS_DATE = 0 AND TARGET_ID_WIKIDATA IS NOT NULL),
  (SELECT COUNT(*) FROM T_WC_WIKIPEDIA_PAGE_LANG_LINK WHERE TIM_UPDATED >= NOW() - INTERVAL 1 DAY AND IS_REDLINK = 0 AND IS_DATE = 0);
