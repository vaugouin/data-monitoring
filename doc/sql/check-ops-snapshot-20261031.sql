-- Did the ops dashboard run today? ops.py persists one row per task/service/host check
-- into T_WC_DATA_MONITORING_SNAPSHOT with SOURCE_DB = 'OPS'.
SELECT DAT_CREAT, COUNT(*) AS N_ROWS, MIN(TIM_UPDATED) AS FIRST_AT, MAX(TIM_UPDATED) AS LAST_AT
FROM T_WC_DATA_MONITORING_SNAPSHOT
WHERE SOURCE_DB = 'OPS'
GROUP BY DAT_CREAT
ORDER BY DAT_CREAT DESC
LIMIT 5;

SELECT TABLE_NAME, METRIC_KEY, DONE_COUNT
FROM T_WC_DATA_MONITORING_SNAPSHOT
WHERE SOURCE_DB = 'OPS' AND DAT_CREAT = CURDATE() AND METRIC_KEY = 'ops_status'
ORDER BY DONE_COUNT DESC, TABLE_NAME;
